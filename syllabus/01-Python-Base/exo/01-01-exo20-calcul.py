# Calculer l’expression suivante en une seule opération arithmétique.
# Faites le produit de la somme de 4 et 5 par la différence entre 10 et 3,
# auquel vous soustrayez 3. 
# Vous divisez le tout par 6 puis vous enlevez 10.
# Quelle est la valeur finale ? 

# division entière : // : x est un entier 
x = ( ( 4 + 5 )*( 10 - 3 ) - 3 ) // 6 - 10
print(x)

# division décimale : / : y est un décimal
y = ( ( 4 + 5 )*( 10 - 3 ) - 3 ) / 6 - 10
print(y)

